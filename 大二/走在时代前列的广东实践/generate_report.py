def set_font(run, name='宋体', size=Pt(10.5), bold=False):
    run.font.name = name
    run._element.rPr.rFonts.set(qn('w:eastAsia'), name)
    run.font.size = size
    run.bold = bold

def set_spacing(paragraph, line_spacing=1.25, space_after=Pt(0)):
    pf = paragraph.paragraph_format
    pf.line_spacing = line_spacing
    if space_after:
        pf.space_after = space_after

def add_heading_styled(doc, text, level=1):
    p = doc.add_paragraph()
    run = p.add_run(text)
    sizes = {0: Pt(16), 1: Pt(14), 2: Pt(12)}
    set_font(run, '宋体', sizes.get(level, Pt(14)), bold=True)
    if level == 0:
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    set_spacing(p, 1.25, Pt(6))
    return p

def add_body(doc, text):
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.first_line_indent = Pt(21)
    pf.line_spacing = 1.25
    run = p.add_run(text)
    set_font(run, '宋体', Pt(10.5))
    return p

def add_image(doc, filename, caption, width_inches=5.0):
    filepath = os.path.join(IMGDIR, filename)
    if os.path.exists(filepath):
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        set_spacing(p, 1.25, Pt(4))
        run = p.add_run()
        run.add_picture(filepath, width=Inches(width_inches))
        p2 = doc.add_paragraph()
        p2.alignment = WD_ALIGN_PARAGRAPH.CENTER
        set_spacing(p2, 1.25, Pt(8))
        run2 = p2.add_run(caption)
        set_font(run2, '宋体', Pt(9))
        return True
    return False

